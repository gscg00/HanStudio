import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge'});
try{
 const context=await browser.newContext({viewport:{width:320,height:568},serviceWorkers:'block',reducedMotion:'reduce'});
 await context.addInitScript(()=>{
   window.SpeechRecognition=class{start(){window.qaRecognizer=this;}abort(){} };
 });
 const page=await context.newPage();
 await page.goto('http://127.0.0.1:8080/?qa#/english/course/lesson/english-b1-1-cause-effect-production-checkpoint');
 await page.getByRole('textbox').waitFor();
 await page.getByRole('textbox').fill('Consequently, the project was delayed.');
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 assert.match(await page.locator('.jp-feedback').innerText(),/¡Muy bien!/);
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('textbox').fill('Although she was tired, she finished the work.');
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 for(const name of ['As','a','result,','the','project','was','delayed.'])await page.getByRole('button',{name,exact:true}).click();
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('textbox').fill('work');
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('button',{name:'🎙 Responder hablando',exact:true}).click();
 await page.getByRole('button',{name:'Cancelar grabación',exact:true}).click();
 await page.getByRole('textbox').fill("What's your opinion?");
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 assert.match(await page.locator('.jp-feedback').innerText(),/¡Muy bien!/);
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('button',{name:'🎙 Responder hablando',exact:true}).click();
 await page.evaluate(()=>window.qaRecognizer.onerror({error:'no-speech'}));
 await page.getByRole('textbox').fill('Although she was tired, she finished the work.');
 await page.getByRole('button',{name:'Comprobar',exact:true}).click();
 assert.match(await page.locator('.jp-feedback').innerText(),/¡Muy bien!/);
 const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,nav:[...document.querySelectorAll('.jp-app-nav button')].map(n=>({text:n.textContent,left:n.getBoundingClientRect().left,right:n.getBoundingClientRect().right}))}));
 assert.ok(layout.scroll<=layout.width+1,JSON.stringify(layout));
 assert.ok(layout.nav.every(n=>n.left>=0&&n.right<=layout.width),JSON.stringify(layout));
 await page.screenshot({path:'/tmp/hanstory-qa-mobile.png',fullPage:true});
 console.log('Voz: cancelar, fallo sin voz y respuesta escrita posterior correctos. Navegación móvil visible.');
 await page.getByRole('button',{name:'Inicio',exact:true}).click();
 await page.getByRole('button',{name:'Estudiar Inglés',exact:true}).click();
 await page.locator('[data-mode="stories"]').click();
 await page.locator('.book-card .open-book').first().click();
 await page.locator('#playback-mode').waitFor();
 assert.equal(await page.locator('#playback-mode option[value="podcast"]').count(),0);
 console.log('Historias: modo Podcast vacío oculto.');
 await context.close();
}finally{await browser.close();}
